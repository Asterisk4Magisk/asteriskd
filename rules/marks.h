#ifndef ASTERISKD_RULES_MARKS_H
#define ASTERISKD_RULES_MARKS_H

#define ASTERISKD_PRIMARY_MARK 0x20000000
#define ASTERISKD_MARK_MASK 0x60000000

/* Wire contract shared with the enhancement module and BPF2SOCKS.
 * The classified bit is reserved for Asterisk DNS decisions. Proxy sockets
 * carry the final routing mark before their first route lookup. */
#define ASTERISKD_DNS_CLASSIFIED_BIT 0x1000000
#define ASTERISKD_DNS_PROXY_DECISION ASTERISKD_DNS_PROXY_ROUTE_MARK
#define ASTERISKD_DNS_DIRECT_MARK 0x41000000
#define ASTERISKD_DNS_PROXY_ROUTE_MARK 0x21000000
#define ASTERISKD_DNS_MARK_MASK 0x61000000

#define ASTERISKD_MARK_STRINGIFY_RAW(value) #value
#define ASTERISKD_MARK_STRINGIFY(value) ASTERISKD_MARK_STRINGIFY_RAW(value)
#define ASTERISKD_MARK_MATCH(value, mask) \
    ASTERISKD_MARK_STRINGIFY(value) "/" ASTERISKD_MARK_STRINGIFY(mask)

#define ASTERISKD_ROUTE_MATCH ASTERISKD_MARK_MATCH(ASTERISKD_PRIMARY_MARK, ASTERISKD_MARK_MASK)
#define ASTERISKD_DNS_CLASSIFIED_MATCH \
    ASTERISKD_MARK_MATCH(ASTERISKD_DNS_CLASSIFIED_BIT, ASTERISKD_DNS_CLASSIFIED_BIT)
#define ASTERISKD_DNS_PROXY_DECISION_MATCH \
    ASTERISKD_MARK_MATCH(ASTERISKD_DNS_PROXY_DECISION, ASTERISKD_DNS_MARK_MASK)
#define ASTERISKD_DNS_DIRECT_MATCH \
    ASTERISKD_MARK_MATCH(ASTERISKD_DNS_DIRECT_MARK, ASTERISKD_DNS_MARK_MASK)
#define ASTERISKD_DNS_PROXY_ROUTE_MATCH \
    ASTERISKD_MARK_MATCH(ASTERISKD_DNS_PROXY_ROUTE_MARK, ASTERISKD_DNS_MARK_MASK)

#endif
